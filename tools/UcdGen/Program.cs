using System.Globalization;
using System.Text;

// Reads pinned UCD files and writes compact range tables as C#.
// usage: UcdGen <ucd-dir> <version> <output.cs>
// Properties are listed in `specs`; adding one is a one-line change.

string ucd = args[0];
string version = args[1];
string output = args[2];

// (C# name, source file, property name or "gc=XX" for a UnicodeData.txt general category)
(string Name, string File, string Prop)[] specs =
[
    ("IdStart", "DerivedCoreProperties.txt", "ID_Start"),
    ("IdContinue", "DerivedCoreProperties.txt", "ID_Continue"),
    ("SpaceSeparator", "UnicodeData.txt", "gc=Zs"),
];

var sb = new StringBuilder();
sb.Append("// <auto-generated>Generated by tools/UcdGen from the Unicode Character Database ").Append(version).Append(". Do not edit.</auto-generated>\n");
sb.Append("namespace RecursiveAI.OneEcma.Unicode;\n\n");
sb.Append("/// <summary>Code point range tables generated from the Unicode Character Database.</summary>\n");
sb.Append("internal static partial class UnicodeTables\n{\n");
sb.Append("    /// <summary>The Unicode version the tables were generated from.</summary>\n");
sb.Append("    internal const string Version = \"").Append(version).Append("\";\n");

foreach (var (name, file, prop) in specs)
{
    var ranges = prop.StartsWith("gc=", StringComparison.Ordinal)
        ? ReadGeneralCategory(Path.Combine(ucd, file), prop[3..])
        : ReadProperty(Path.Combine(ucd, file), prop);
    ranges.Sort((a, b) => a.Lo.CompareTo(b.Lo));
    var merged = new List<(int Lo, int Hi)>();
    foreach (var r in ranges)
    {
        if (merged.Count > 0 && r.Lo <= merged[^1].Hi + 1)
        {
            merged[^1] = (merged[^1].Lo, Math.Max(merged[^1].Hi, r.Hi));
        }
        else
        {
            merged.Add(r);
        }
    }

    sb.Append("\n    /// <summary>Inclusive code point ranges of ").Append(prop).Append(" as lo, hi pairs, sorted.</summary>\n");
    sb.Append("    internal static ReadOnlySpan<int> ").Append(name).Append("Ranges => [");
    for (int i = 0; i < merged.Count; i++)
    {
        if (i % 8 == 0)
        {
            sb.Append("\n        ");
        }

        sb.Append(merged[i].Lo.ToString(CultureInfo.InvariantCulture)).Append(", ")
          .Append(merged[i].Hi.ToString(CultureInfo.InvariantCulture)).Append(", ");
    }

    sb.Append("\n    ];\n");
}

sb.Append("}\n");
File.WriteAllText(output, sb.ToString());
return 0;

static List<(int Lo, int Hi)> ReadProperty(string path, string prop)
{
    var list = new List<(int, int)>();
    foreach (string raw in File.ReadLines(path))
    {
        int hash = raw.IndexOf('#', StringComparison.Ordinal);
        string line = (hash >= 0 ? raw[..hash] : raw).Trim();
        if (line.Length == 0)
        {
            continue;
        }

        string[] parts = line.Split(';');
        if (parts.Length < 2 || parts[1].Trim() != prop)
        {
            continue;
        }

        string[] cp = parts[0].Trim().Split("..");
        int lo = int.Parse(cp[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        int hi = cp.Length > 1 ? int.Parse(cp[1], NumberStyles.HexNumber, CultureInfo.InvariantCulture) : lo;
        list.Add((lo, hi));
    }

    return list;
}

static List<(int Lo, int Hi)> ReadGeneralCategory(string path, string gc)
{
    var list = new List<(int, int)>();
    int pendingFirst = -1;
    foreach (string line in File.ReadLines(path))
    {
        string[] f = line.Split(';');
        if (f.Length < 3)
        {
            continue;
        }

        int cp = int.Parse(f[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        if (f[1].EndsWith(", First>", StringComparison.Ordinal))
        {
            pendingFirst = cp;
            continue;
        }

        int lo = f[1].EndsWith(", Last>", StringComparison.Ordinal) ? pendingFirst : cp;
        if (f[2] == gc)
        {
            list.Add((lo, cp));
        }
    }

    return list;
}
