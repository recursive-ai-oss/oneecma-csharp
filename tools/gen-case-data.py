#!/usr/bin/env python3
"""Generates src/RecursiveAI.OneEcma/Unicode/CaseData.g.cs from the pinned UCD files.

usage: tools/gen-case-data.py <ucd-dir> <output.cs>

Inputs (UCD 17.0.0): UnicodeData.txt (simple mappings), SpecialCasing.txt (unconditional full mappings),
DerivedCoreProperties.txt (Cased, Case_Ignorable, used by the Final_Sigma rule).
The output is deterministic.
"""
import sys, os


def parse_ranges(path, prop):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        rng, name = [x.strip() for x in line.split(";")][:2]
        if name != prop:
            continue
        if ".." in rng:
            a, b = rng.split("..")
        else:
            a = b = rng
        out.append((int(a, 16), int(b, 16)))
    out.sort()
    merged = []
    for a, b in out:
        if merged and a <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(b, merged[-1][1]))
        else:
            merged.append((a, b))
    return merged


def main():
    ucd, outp = sys.argv[1], sys.argv[2]
    upper, lower = {}, {}
    for line in open(os.path.join(ucd, "UnicodeData.txt"), encoding="utf-8"):
        f = line.rstrip("\n").split(";")
        cp = int(f[0], 16)
        if f[12]:
            upper[cp] = [int(f[12], 16)]
        if f[13]:
            lower[cp] = [int(f[13], 16)]
    for line in open(os.path.join(ucd, "SpecialCasing.txt"), encoding="utf-8"):
        body = line.split("#")[0].strip()
        if not body:
            continue
        f = [x.strip() for x in body.split(";")]
        if len(f) > 4 and f[4]:
            continue  # conditional mapping: handled by the caller (Final_Sigma) or language-specific
        cp = int(f[0], 16)
        lo = [int(x, 16) for x in f[1].split()]
        up = [int(x, 16) for x in f[3].split()]
        if lo != lower.get(cp, [cp]):
            lower[cp] = lo
        if up != upper.get(cp, [cp]):
            upper[cp] = up
    dcp = os.path.join(ucd, "DerivedCoreProperties.txt")
    cased = parse_ranges(dcp, "Cased")
    ign = parse_ranges(dcp, "Case_Ignorable")

    def emit(name, table):
        keys = sorted(table)
        seq = []
        vals = []
        for k in keys:
            m = table[k]
            if len(m) == 1:
                vals.append(m[0])
            else:
                vals.append(-(len(seq) + 1))
                seq.extend([len(m)] + m)
        return keys, vals, seq

    def arr(name, items, doc):
        s = "    /// <summary>%s</summary>\n    internal static ReadOnlySpan<int> %s => [\n" % (doc, name)
        for i in range(0, len(items), 16):
            s += "        " + ", ".join(str(x) for x in items[i:i + 16]) + ",\n"
        return s + "    ];\n\n"

    o = "// <auto-generated>Generated by tools/gen-case-data.py from the Unicode Character Database 17.0.0. Do not edit.</auto-generated>\n"
    o += "namespace RecursiveAI.OneEcma.Unicode;\n\n/// <summary>Full case mapping data: UnicodeData simple mappings overridden by the unconditional SpecialCasing entries.</summary>\n"
    o += "internal static class CaseData\n{\n"
    for nm, tb in (("Upper", upper), ("Lower", lower)):
        k, v, s = emit(nm, tb)
        o += arr(nm + "Keys", k, "Code points with a %scase mapping, sorted." % nm.lower())
        o += arr(nm + "Values", v, "The mapping of each key: a code point, or minus (offset + 1) into %sSeq." % nm)
        o += arr(nm + "Seq", s, "Multi-code-point mappings as length followed by the code points.")
    flat = lambda r: [x for p in r for x in p]
    o += arr("CasedRanges", flat(cased), "Inclusive ranges of the Cased property.")
    o += arr("CaseIgnorableRanges", flat(ign), "Inclusive ranges of the Case_Ignorable property.")
    o += "}\n"
    open(outp, "w", encoding="utf-8", newline="\n").write(o)


main()
