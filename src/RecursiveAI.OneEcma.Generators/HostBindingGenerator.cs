using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace RecursiveAI.OneEcma.Generators;

/// <summary>
/// Writes the script bindings for every type marked <c>[JsExport]</c>: one <c>{Type}JsBinding</c> class per type, and a
/// <c>JsExports.InstallAll(realm)</c> that installs the lot. Everything is plain C# over the public host API, so nothing needs
/// reflection at run time.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class HostBindingGenerator : IIncrementalGenerator
{
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<GenResult> types = context.SyntaxProvider.ForAttributeWithMetadataName(
            Classifier.ExportAttr,
            static (node, _) => node is TypeDeclarationSyntax or EnumDeclarationSyntax,
            static (ctx, _) => Generate(ctx));

        context.RegisterSourceOutput(types, static (spc, r) =>
        {
            foreach (Diagnostic d in r.Diagnostics)
            {
                spc.ReportDiagnostic(d);
            }

            if (r.Source is not null)
            {
                spc.AddSource(r.HintName, r.Source);
            }
        });

        context.RegisterSourceOutput(types.Collect().Combine(context.CompilationProvider.Combine(context.AnalyzerConfigOptionsProvider)), static (spc, pair) =>
        {
            ImmutableArray<GenResult> all = pair.Left;
            var installed = all.Where(r => r.Install is not null).OrderBy(r => r.HintName, StringComparer.Ordinal).ToList();
            if (installed.Count == 0)
            {
                return;
            }

            foreach (IGrouping<string, GenResult> g in installed.GroupBy(r => r.JsName))
            {
                List<GenResult> items = g.ToList();
                if (items.Count > 1 && items[1].Location is { } loc)
                {
                    spc.ReportDiagnostic(Diagnostic.Create(Descriptors.NameCollision, loc, items[0].TypeName, items[1].TypeName, g.Key, "the global object"));
                }
            }

            pair.Right.Right.GlobalOptions.TryGetValue("build_property.RootNamespace", out string? root);
            string ns = SanitizeNamespace(string.IsNullOrWhiteSpace(root) ? pair.Right.Left.AssemblyName ?? "Generated" : root!);
            bool allPublic = installed.All(r => r.IsPublic);
            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n#nullable enable\n#pragma warning disable\n\nusing RecursiveAI.OneEcma;\n\nnamespace ").Append(ns).Append("\n{\n");
            sb.Append("    /// <summary>Installs every <c>[JsExport]</c> type of this assembly into a realm.</summary>\n");
            sb.Append("    ").Append(allPublic ? "public" : "internal").Append(" static class JsExports\n    {\n");
            sb.Append("        /// <summary>Installs all exported types, so scripts see their classes and enums as globals and <see cref=\"JsRealm.Wrap\"/> knows their instances.</summary>\n");
            sb.Append("        /// <param name=\"realm\">The realm.</param>\n        public static void InstallAll(JsRealm realm)\n        {\n");
            foreach (GenResult r in installed)
            {
                sb.Append("            realm.Install(").Append(r.Install).Append(".JsType);\n");
            }

            sb.Append("        }\n\n        /// <summary>The script names of the exported types, in install order.</summary>\n        public static readonly string[] Names = [");
            sb.Append(string.Join(", ", installed.Select(r => BindingEmitter.Lit(r.JsName))));
            sb.Append("];\n    }\n}\n");
            spc.AddSource("JsExports.g.cs", sb.ToString());
        });
    }

    private static string SanitizeNamespace(string assemblyName)
    {
        var sb = new StringBuilder();
        foreach (char c in assemblyName)
        {
            sb.Append(char.IsLetterOrDigit(c) || c == '.' || c == '_' ? c : '_');
        }

        string s = sb.ToString().Trim('.');
        return s.Length == 0 || char.IsDigit(s[0]) ? "_" + s : s;
    }

    private static GenResult Generate(GeneratorAttributeSyntaxContext ctx)
    {
        var type = (INamedTypeSymbol)ctx.TargetSymbol;
        var diags = new List<Diagnostic>();
        ExportInfo export = Classifier.GetExport(type)!;
        Location? loc = type.Locations.FirstOrDefault();
        string typeName = type.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat);
        string hint = ExportInfo.BindingNameOf(type, true).Replace("global::", string.Empty) + ".g.cs";

        void Bad(string why, string fix) =>
            diags.Add(Diagnostic.Create(Descriptors.UnsupportedDeclaration, loc ?? Location.None, typeName, why, fix));

        if (type.IsGenericType)
        {
            Bad("generic types are not supported", "export a closed subclass or a non-generic wrapper");
        }
        else if (type.IsRefLikeType)
        {
            Bad("ref structs cannot be held by script", "use a normal struct or class");
        }
        else if (type.TypeKind == TypeKind.Delegate)
        {
            Bad("delegates are not exported", "pass Func<...>/Action<...> parameters instead");
        }
        else if (HasPrivateContainer(type))
        {
            Bad("it is nested in a type that is not at least internal, so generated code cannot see it", "make the type and its containers internal or public");
        }

        if (type.TypeKind == TypeKind.Enum)
        {
            // Enums are always strings in script; the kind option does not apply.
        }
        else if (export.IsValue && (type.TypeKind == TypeKind.Interface || type.IsStatic || type.IsAbstract))
        {
            diags.Add(Diagnostic.Create(Descriptors.ValueKindConflict, loc ?? Location.None, typeName, "Value", "an interface, static or abstract class cannot be built from a script object", "use JsExportKind.Reference or remove the Kind setting"));
        }
        else if (!export.IsValue && type.TypeKind == TypeKind.Struct)
        {
            diags.Add(Diagnostic.Create(Descriptors.ValueKindConflict, loc ?? Location.None, typeName, "Reference", "a struct is copied when handed to script, so a shared handle would silently refer to a copy", "use JsExportKind.Value, or make it a class"));
        }

        if (diags.Count > 0)
        {
            return new GenResult(hint, null, diags, null, export.JsName, typeName, false, loc);
        }

        var cls = new Classifier();
        var emitter = new BindingEmitter(type, export, cls, diags);
        string source = emitter.Emit(out bool installed);
        bool hasErrors = diags.Any(d => d.Severity == DiagnosticSeverity.Error);
        return new GenResult(hint, hasErrors ? null : source, diags, installed && !hasErrors ? ExportInfo.BindingNameOf(type, true) : null, export.JsName, typeName, emitter.IsPublic, loc);
    }

    private static bool HasPrivateContainer(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? t = type; t is not null; t = t.ContainingType)
        {
            if (t.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal or Accessibility.ProtectedOrInternal && t.ContainingType is not null)
            {
                return true;
            }
        }

        return false;
    }

    private sealed class GenResult
    {
        internal GenResult(string hintName, string? source, List<Diagnostic> diagnostics, string? install, string jsName, string typeName, bool isPublic, Location? location)
        {
            HintName = hintName;
            Source = source;
            Diagnostics = diagnostics;
            Install = install;
            JsName = jsName;
            TypeName = typeName;
            IsPublic = isPublic;
            Location = location;
        }

        internal string HintName { get; }

        internal string? Source { get; }

        internal List<Diagnostic> Diagnostics { get; }

        internal string? Install { get; }

        internal string JsName { get; }

        internal string TypeName { get; }

        internal bool IsPublic { get; }

        internal Location? Location { get; }
    }
}
